"""Generate the small, exact-English-keyed German usage fallback table offline.

The input mirrors the reviewed Web translations; it is not a list of new
compatibility claims. The firmware build uses the checked-in header, not Web
files, network access or an enlarged persistent database schema.
"""
import argparse
import json
from pathlib import Path


FW = Path(__file__).resolve().parents[1]
INPUT = FW / "data/usage-translations.de.json"
OUTPUT = FW / "application/src/app/amiidb/view/amiibo_usage_de.h"


def render(data):
    if not isinstance(data, dict) or data.get("schemaVersion") != 1 or not isinstance(data.get("texts"), dict):
        raise ValueError("Expected reviewed usage translation schema 1")
    texts = data["texts"]
    if not texts or len(texts) > 32:
        raise ValueError("Sparse firmware translation table must contain 1..32 entries")
    rows = []
    for source, translated in texts.items():
        for value in (source, translated):
            if not isinstance(value, str) or not value.strip() or any(ord(ch) < 32 for ch in value):
                raise ValueError("Usage translations must be nonempty text without control characters")
            value.encode("utf-8")
        rows.append("    {%s, %s}," % (json.dumps(source, ensure_ascii=False),
                                       json.dumps(translated, ensure_ascii=False)))
    return """/* Generated by fw/scripts/generate_usage_de.py. Do not edit.
 * Editorial translations of exact existing English catalogue text, not new
 * game compatibility evidence. Unknown/changed text falls back to English. */
#ifndef AMIIBO_USAGE_DE_H
#define AMIIBO_USAGE_DE_H
#include <stddef.h>
#include <string.h>
static const struct { const char *en; const char *de; } amiibo_usage_de_texts[] = {
""" + "\n".join(rows) + """
};
static const char *amiibo_usage_de(const char *english) {
    if (!english) return "";
    for (size_t i = 0; i < sizeof(amiibo_usage_de_texts) / sizeof(amiibo_usage_de_texts[0]); ++i)
        if (!strcmp(english, amiibo_usage_de_texts[i].en)) return amiibo_usage_de_texts[i].de;
    return english;
}
#endif
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if checked-in output is stale; do not write")
    args = parser.parse_args()
    expected = render(json.loads(INPUT.read_text(encoding="utf-8")))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            parser.exit(1, "German firmware usage table is stale; regenerate it.\n")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
