"""Pack reviewed German LCD text using a single-level UTF-8 phrase dictionary."""
import argparse
from collections import Counter
import json
from pathlib import Path
import re


FW = Path(__file__).resolve().parents[1]
INPUT = FW / "data/usage-translations.de.json"
OUTPUT = FW / "application/src/app/amiidb/view/amiibo_usage_de.h"
MAX_TEXTS = 54                    # Number of distinct English keys in this catalogue.
MAX_UTF8 = 191                    # Upper bound on caller-owned decode space.
MAX_TOKENS = 31                   # Spare control bytes; 0 terminates every C string.


def pack(values):
    """Replace profitable repeated word sequences; never put tokens inside tokens."""
    encoded = list(values)
    phrases = []
    for token in range(1, MAX_TOKENS + 1):
        counts = Counter()
        for row in encoded:
            for plain in re.split(r"[\x00-\x1f]", row):
                words = re.findall(r"\w+|\s+|[^\w\s]", plain)
                for first in range(len(words)):
                    for end in range(first + 1, min(first + 20, len(words)) + 1):
                        counts["".join(words[first:end])] += 1
        if not counts:
            break

        def benefit(phrase):
            size = len(phrase.encode("utf-8"))
            # Each reference costs one byte; each dictionary entry costs the
            # literal, a NUL, and a native 32-bit flash pointer.
            return counts[phrase] * (size - 1) - size - 5

        best = max(counts, key=lambda phrase: (benefit(phrase), len(phrase), phrase))
        if benefit(best) <= 0:
            break
        encoded = [row.replace(best, chr(token)) for row in encoded]
        phrases.append(best)
    return encoded, phrases


def literal(value):
    # Use fixed-width octal so a digit after a token cannot extend its escape.
    return '"' + ''.join("\\%03o" % ord(ch) if ord(ch) < 32 else
                         "\\" + ch if ch in '\\"' else ch for ch in value) + '"'


def render(data):
    if not isinstance(data, dict) or data.get("schemaVersion") != 1 or not isinstance(data.get("texts"), dict):
        raise ValueError("Expected reviewed usage translation schema 1")
    texts = data["texts"]
    if not 1 <= len(texts) <= MAX_TEXTS:
        raise ValueError(f"Expected 1..{MAX_TEXTS} LCD translations")
    for english, german in texts.items():
        for value in (english, german):
            if not isinstance(value, str) or not value.strip() or any(ord(ch) < 32 for ch in value):
                raise ValueError("Expected nonempty text without control characters")
            value.encode("utf-8")
        if len(german.encode("utf-8")) > MAX_UTF8:
            raise ValueError("LCD translation exceeds the permitted scratch space")
    keys = sorted(texts)  # UTF-8 byte ordering agrees with strcmp on valid UTF-8 strings.
    values = [texts[key] for key in keys]
    encoded, phrases = pack(values)
    rows = ",\n".join("    {%s, %s}" % (literal(en), literal(de)) for en, de in zip(keys, encoded))
    # Always emit a legal nonempty C array, including when no phrase repeats.
    words = ",\n".join("    " + literal(word) for word in phrases) or "    NULL"
    limit = max(len(value.encode("utf-8")) for value in values) + 1
    return f"""/* Generated by fw/scripts/generate_usage_de.py. Do not edit. */
#ifndef AMIIBO_USAGE_DE_H
#define AMIIBO_USAGE_DE_H
#include <stddef.h>
#include <string.h>
#define AMIIBO_USAGE_DE_BUFFER_BYTES {limit}
#define AMIIBO_USAGE_DE_TOKEN_COUNT {len(phrases)}
static const char *const amiibo_usage_de_phrases[] = {{
{words}
}};
static const struct {{ const char *en; const char *encoded; }} amiibo_usage_de_texts[] = {{
{rows}
}};
""" + r'''
/* Only the active draw owns the scratch space. Unreviewed English, missing
 * scratch or an undersized destination always return the original fallback. */
static const char *amiibo_usage_de(const char *english, char *out, size_t capacity) {
    if (!english) return "";
    if (!out || capacity < AMIIBO_USAGE_DE_BUFFER_BYTES) return english;
    size_t lo = 0, hi = sizeof(amiibo_usage_de_texts) / sizeof(amiibo_usage_de_texts[0]);
    while (lo < hi) {
        const size_t mid = lo + (hi - lo) / 2;
        const int order = strcmp(english, amiibo_usage_de_texts[mid].en);
        if (order < 0) hi = mid;
        else if (order > 0) lo = mid + 1;
        else {
            const unsigned char *p = (const unsigned char *)amiibo_usage_de_texts[mid].encoded;
            char *dst = out;
            while (*p) {
                if (*p <= AMIIBO_USAGE_DE_TOKEN_COUNT) {
                    const char *word = amiibo_usage_de_phrases[*p - 1];
                    while (*word) *dst++ = *word++;
                } else {
                    *dst++ = (char)*p;
                }
                ++p;
            }
            *dst = '\0';
            return out;
        }
    }
    return english;
}
#endif
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail for a stale generated header")
    args = parser.parse_args()
    expected = render(json.loads(INPUT.read_text(encoding="utf-8")))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            parser.exit(1, "German firmware usage table is stale; regenerate it.\n")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
