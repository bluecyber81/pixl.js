"""Check the selected display profile and SPI commands in the final Cortex-M4 application."""

import argparse
from pathlib import Path
from subprocess import check_output
import struct

from check_stack_watermark_elf import tool
from unicorn import Uc, UC_ARCH_ARM, UC_HOOK_CODE, UC_HOOK_MEM_WRITE, UC_MODE_MCLASS, UC_MODE_THUMB
from unicorn.arm_const import (UC_CPU_ARM_CORTEX_M4, UC_ARM_REG_LR, UC_ARM_REG_MSP,
                               UC_ARM_REG_PC, UC_ARM_REG_R0, UC_ARM_REG_R1,
                               UC_ARM_REG_R2, UC_ARM_REG_R3)


def check_game_pages(cpu, symbols, call, respond, column):
    """Observe the D/C pin and the DMA bytes generated by the linked game driver."""
    pages = []
    is_data = None

    def track_dc(machine, access, address, size, value, data):
        nonlocal is_data
        assert size == 4 and value == 1 << 28  # P0.28 is D/C on both boards.
        is_data = address == 0x50000508  # GPIO OUTSET or OUTCLR

    def acquire(*args):
        pages.append([])
        respond()

    def transfer(*args):
        nonlocal is_data
        desc = cpu.mem_read(cpu.reg_read(UC_ARM_REG_R0), 16)
        rx_ptr, rx_len, tx_ptr, tx_len = struct.unpack('<IIII', desc)
        assert (rx_ptr, rx_len, tx_len) == (0, 0, 1) and is_data is not None
        pages[-1].append((is_data, cpu.mem_read(tx_ptr, 1)[0]))
        is_data = None
        respond(0)  # NRF_SUCCESS

    hooks = [cpu.hook_add(UC_HOOK_MEM_WRITE, track_dc, begin=0x50000508, end=0x5000050c)]
    for name, handler in (('hal_spi_bus_aquire', acquire), ('hal_spi_bus_xfer', transfer),
                          ('hal_spi_bus_release', lambda *args: respond())):
        addr = symbols[name]
        hooks.append(cpu.hook_add(UC_HOOK_CODE, handler, begin=addr, end=addr))

    edge_pages = [bytes([0x80 | page]) + bytes(126) + bytes([0x40 | page]) for page in range(8)]
    clear_pages = [bytes(128)] * 8
    for rotation in (0, 1):
        call('mui_u8g2_set_flip_display', rotation)
        for clear, expected_pages in ((True, clear_pages), (False, edge_pages)):
            pages.clear()
            if clear:
                call('JOY_OLED_clear')
            else:
                for page, pixels in enumerate(expected_pages):
                    call('JOY_OLED_data_start', page)
                    for value in pixels:
                        call('JOY_OLED_send', value)
                    call('JOY_OLED_end')
            assert len(pages) == 8, len(pages)
            for page, received in enumerate(pages):
                address = [(False, 0xb0 | page), (False, 0x10), (False, column)]
                assert received[:3] == address, (rotation, page, received[:3], address)
                assert received[3:] == [(True, value) for value in expected_pages[page]], (rotation, page)
    for hook in hooks:
        cpu.hook_del(hook)
    print(f'PASS game clear and edge pixels across columns {column}..{column + 127}, '
          'eight pages in both menu orientations.')


def verify(elf, binary, board='LCD'):
    rows = (line.split() for line in check_output([tool('nm'), '-n', elf], text=True).splitlines())
    symbols = {row[2]: int(row[0], 16) for row in rows if len(row) == 3}
    cpu = Uc(UC_ARCH_ARM, UC_MODE_MCLASS | UC_MODE_THUMB)
    cpu.ctl_set_cpu_model(UC_CPU_ARM_CORTEX_M4)
    cpu.mem_map(0, 0x80000)
    cpu.mem_map(0x20000000, 0x10000)
    cpu.mem_map(0x50000000, 0x1000)  # GPIO registers for display setup and game D/C.
    cpu.mem_write(symbols['__isr_vector'], binary.read_bytes())
    top = symbols['__StackTop']

    def call(name, *args):
        for reg, value in zip((UC_ARM_REG_R0, UC_ARM_REG_R1, UC_ARM_REG_R2, UC_ARM_REG_R3), args):
            cpu.reg_write(reg, value)
        cpu.reg_write(UC_ARM_REG_MSP, top)
        cpu.reg_write(UC_ARM_REG_LR, 0x101)
        cpu.emu_start(symbols[name] | 1, 0x100, count=50000)
        assert cpu.reg_read(UC_ARM_REG_PC) == 0x100 and cpu.reg_read(UC_ARM_REG_MSP) == top
        return cpu.reg_read(UC_ARM_REG_R0)

    def respond(value=1):
        cpu.reg_write(UC_ARM_REG_R0, value)
        cpu.reg_write(UC_ARM_REG_PC, cpu.reg_read(UC_ARM_REG_LR))

    # Obtain the actual application-owned display instance used by the setter.
    contexts = []
    def remember_context(machine, address, size, data):
        contexts.append(cpu.reg_read(UC_ARM_REG_R0))
        respond()

    addr = symbols['u8x8_SetContrast']
    hook = cpu.hook_add(UC_HOOK_CODE, remember_context, begin=addr, end=addr)
    call('mui_u8g2_set_contrast_level', 80)
    cpu.hook_del(hook)
    context, = contexts

    # Setup, rotation, drawing and command encoding run from the linked BIN.
    commands = []
    def capture_byte(machine, address, size, data):
        if cpu.reg_read(UC_ARM_REG_R1) == 23:  # U8X8_MSG_BYTE_SEND
            commands.extend(cpu.mem_read(cpu.reg_read(UC_ARM_REG_R3), cpu.reg_read(UC_ARM_REG_R2)))
        respond()

    byte_cb = symbols['u8x8_HW_com_spi_nrf52832']
    gpio_cb = symbols['u8g2_nrf_gpio_and_delay_spi_cb']
    cpu.hook_add(UC_HOOK_CODE, capture_byte, begin=byte_cb, end=byte_cb)
    cpu.hook_add(UC_HOOK_CODE, lambda *args: respond(), begin=gpio_cb, end=gpio_cb)
    oled = board == 'OLED'
    if oled:
        assert 'u8g2_Setup_sh1106_128x64_noname_f' in symbols
        assert 'u8g2_Setup_st7567_enh_dg128064_f' not in symbols
        attach = symbols['hal_spi_bus_attach']
        cpu.hook_add(UC_HOOK_CODE, lambda *args: respond(), begin=attach, end=attach)
        call('mui_u8g2_init', context)
        assert 0xAE in commands and commands[-1] == 0xAF, commands
        driver_info = 'u8x8_sh1106_128x64_noname_display_info'
    else:
        call('u8g2_Setup_st7567_enh_dg128064_f', context, symbols['u8g2_cb_r0'], byte_cb | 1, gpio_cb | 1)
        driver_info = 'u8x8_st7567_enh_dg128064_display_info'
    info = cpu.mem_read(symbols[driver_info], 24)
    assert tuple(info[16:18]) == (16, 8) and struct.unpack_from('<HH', info, 20) == (128, 64)
    height_ptr = symbols['__HeapBase']
    buffer = call('u8g2_m_16_8_f', height_ptr)
    assert cpu.mem_read(height_ptr, 1) == b'\x08'
    for rotate, index, mask in ((0, 0, 1), (1, 1023, 128)):
        call('mui_u8g2_set_flip_display', rotate)
        cpu.mem_write(buffer, bytes(1024))
        call('u8g2_DrawPixel', context, 0, 0)
        expected = bytearray(1024)
        expected[index] = mask
        assert bytes(cpu.mem_read(buffer, 1024)) == expected

    check_game_pages(cpu, symbols, call, respond, 2 if oled else 0)

    levels = []
    for percent in range(256):
        commands.clear()
        call('mui_u8g2_set_contrast_level', percent)
        effective = min(100, max(1 if oled else 60, percent))
        expected = (effective - 1) * 255 // 99
        if not oled:
            expected >>= 2
        assert commands == [0x81, expected], (percent, commands, expected)
        levels.append(expected)
    if oled:
        assert len(set(levels)) == 100
        assert bytes(info[18:20]) == bytes((2, 2))
        commands.clear()
        call('u8g2_SendBuffer', context)
        # Each of the eight SH1106 pages starts at physical column two.
        expected = []
        pixels = bytes(cpu.mem_read(buffer, 1024))
        for page in range(8):
            expected.extend([0x40, 0x10, 0x02, 0xB0 + page])
            expected.extend(pixels[128 * page:128 * (page + 1)])
        assert commands == expected, (len(commands), commands[:10])
        commands.clear()
        call('mui_u8g2_deinit', context)
        assert commands == [0xAE], commands
        print('PASS linked OLED SH1106 init/on/off, 128x64, all eight framebuffer pages, '
              'rotation and 256 contrast inputs (100 levels).')
    else:
        assert len(set(levels)) == 27
        print('PASS linked LCD ST7567 128x64, 1024 framebuffer bytes, opposite corner at 180 degrees; '
              '256 input values produced contrast command 0x81 and 27 levels (37..63).')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('elf', type=Path)
    parser.add_argument('binary', type=Path)
    parser.add_argument('--board', choices=['LCD', 'OLED'], default='LCD')
    args = parser.parse_args()
    verify(args.elf, args.binary, args.board)
